#!/usr/bin/env python3
"""VL-FOUNDRY scaffolder — generates a new scanner with the 7-check skeleton.

Usage:
  python scripts/forge_scanner.py <module> <scanner_name> [--tier=<tier_dir>]

Examples:
  python scripts/forge_scanner.py webapp graphql_introspection --tier=tier11_logic
  python scripts/forge_scanner.py vuln new_cve

The scaffold ships with the 7 Definition-of-Done checks pre-wired:
  1. precheck_target via the module's safe_get / web_url helper
  2. uniform_shape via standard_response / vuln_response
  3. POSITIVE emit when target is clean
  4. severity / cvss / cwe / owasp fields filled (placeholders)
  5. remediation field
  6. evidence_marker field
  7. wall-clock timeout

The intent is that the builder fills in scan logic, not boilerplate.
After scaffolding, run:
  $ python scripts/score_module.py <module> --verbose
to confirm the new scanner inherits the module's quality bar.
"""
