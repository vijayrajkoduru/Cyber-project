def scaffold(module: str, name: str, tier: str | None) -> Path:
    if module not in TEMPLATES:
        sys.exit(f"unsupported module: {module} (have: {sorted(TEMPLATES)})")

    base = ROOT / "tools" / module
    if tier:
        base = base / tier
    base.mkdir(parents=True, exist_ok=True)

    out = base / f"{name}.py"
    if out.exists():
        sys.exit(f"file already exists: {out}")

    out.write_text(TEMPLATES[module].format(name=name), encoding="utf-8")
    return out


def main():
    ap = argparse.ArgumentParser(description="Scaffold a new VL-FOUNDRY scanner")
    ap.add_argument("module", help="Module: vuln|webapp|recon")
    ap.add_argument("name", help="Scanner name (snake_case, no .py)")
    ap.add_argument("--tier", default=None,
                    help="Tier subdirectory (e.g. tier11_logic)")
    args = ap.parse_args()

    path = scaffold(args.module, args.name, args.tier)
    rel = path.relative_to(ROOT)
    print(f"✓ created {rel}")
    print(f"\nNext steps:")
    print(f"  1. Fill in _scan() with real scan logic")
